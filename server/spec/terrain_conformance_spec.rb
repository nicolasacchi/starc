    end

    it "returns a unit-length normal everywhere it samples" do
      ([[0.0, 0.0], [20.25, 64.5], [64.5, 128.0], [128.0, 191.75], [191.75, 255.0], [255.0, 255.0]] +
       POINT_SAMPLES.first(20).map { |(x, z, _)| [x, z] }).each do |(x, z)|
        n = terrain.normal_at(x, z)
        expect(Math.sqrt(n.sum { |c| c * c })).to be_within(1e-12).of(1.0), "normal at (#{x}, #{z}) is not unit length"
        expect(n[1]).to be > 0.0, "normal at (#{x}, #{z}) points into the ground"
        expect(terrain.slope(x, z)).to be_within(1e-12).of(1.0 - n[1])
      end
    end
  end

  describe "#passable?" do
    it "agrees with height_at > WATER_LEVEL at every test point" do
      points = ([[0.0, 0.0], [1.0, 1.0], [5.5, 5.5], [20.25, 20.25], [64.0, 64.0], [100.0, 100.0],
                 [128.5, 128.5], [200.0, 200.0], [250.0, 250.0], [255.9, 255.9]] +
                POINT_SAMPLES.map { |(x, z, _)| [x, z] } + SLOPE_POINTS)
      points.each do |(x, z)|
        expected = terrain.height_at(x, z) > described_class::WATER_LEVEL
        expect(terrain.passable?(x, z)).to be(expected), "passable? disagrees at (#{x}, #{z})"
      end
    end

    it "exposes the same water level the passability test uses" do
      expect(terrain.water_level).to eq(described_class::WATER_LEVEL)
      expect(terrain.water_level).to eq(0.0)
    end
  end

  describe "bilinear interpolation" do
    it "matches the hard-coded half-metre sample on a slope" do
      expect(terrain.height_at(SLOPE_X, SLOPE_Z)).to eq(SLOPE_HEIGHTS[0])
      expect(terrain.height_at(SLOPE_X + 0.5, SLOPE_Z)).to eq(SLOPE_HEIGHTS[1])
      expect(terrain.height_at(SLOPE_X + 1.0, SLOPE_Z)).to eq(SLOPE_HEIGHTS[2])
    end

    it "does not snap to the nearest lattice sample" do
      expect(terrain.height_at(SLOPE_X + 0.5, SLOPE_Z))
        .not_to eq(terrain.height_at(SLOPE_X, SLOPE_Z))
      expect(terrain.height_at(SLOPE_X + 0.5, SLOPE_Z))
        .not_to eq(terrain.height_at(SLOPE_X + 1.0, SLOPE_Z))
    end

    it "returns the exact midpoint of the two integer samples" do
      midpoint = (SLOPE_HEIGHTS[0] + SLOPE_HEIGHTS[2]) / 2
      expect(terrain.height_at(SLOPE_X + 0.5, SLOPE_Z)).to eq(midpoint)
      expect(SLOPE_HEIGHTS[1]).to eq(midpoint)
    end

    it "interpolates a quarter and three-quarter step too" do
      a = terrain.height_at(SLOPE_X, SLOPE_Z)
      b = terrain.height_at(SLOPE_X + 1, SLOPE_Z)
      expect(terrain.height_at(SLOPE_X + 0.25, SLOPE_Z)).to be_within(1e-12).of(a + ((b - a) * 0.25))
      expect(terrain.height_at(SLOPE_X + 0.75, SLOPE_Z)).to be_within(1e-12).of(a + ((b - a) * 0.75))
    end
  end

  describe "caching" do
    after { described_class.clear_cache! }

    it "returns the identical object for the same map id" do
      expect(described_class.for(CONFORMANCE_MAP_ID)).to be(described_class.for(CONFORMANCE_MAP_ID))
    end

    it "rebuilds to the same heights after clear_cache!" do
      before = terrain.height_at(128.0, 128.0)
      described_class.clear_cache!
      expect(described_class.cached?(CONFORMANCE_MAP_ID)).to be(false)
      after_rebuild = described_class.for(CONFORMANCE_MAP_ID)
      expect(after_rebuild).not_to be(terrain)
      expect(after_rebuild.height_at(128.0, 128.0)).to eq(before)
      expect(after_rebuild.height_at(SLOPE_X + 0.5, SLOPE_Z)).to eq(SLOPE_HEIGHTS[1])
    end
  end

  describe "per-map independence" do
    after { described_class.clear_cache! }

    it "produces a different height field for a different map id" do
      other = described_class.for(CONFORMANCE_OTHER_MAP_ID)
      expect(other).not_to be(terrain)
      expect(other.height_at(128.0, 128.0)).to eq(OTHER_MAP_CENTRE)
      expect(other.height_at(128.0, 128.0)).not_to eq(terrain.height_at(128.0, 128.0))
    end

    it "raises for an unknown map id instead of inventing terrain" do
      expect { described_class.for("atlantis") }.to raise_error(ArgumentError)
    end
  end
